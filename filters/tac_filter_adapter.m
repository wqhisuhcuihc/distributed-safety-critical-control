function [u_safe, error_vector, used_filter] = tac_filter_adapter( ...
    pos, u_aim, cfg, filter_type)
%TAC_FILTER_ADAPTER Single filter interface for every scenario and scale.

    if nargin < 4 || isempty(filter_type)
        filter_type = cfg.filter_type;
    end
    filter_type = lower(string(filter_type));
    switch filter_type
        case "sparse"
            [u_safe,error_vector] = tac_filter_sparse(pos,u_aim, ...
                cfg.agent_radius,cfg.safe_distance,cfg.wifi_distance, ...
                cfg.static_obstacle,cfg.obstacle_radius, ...
                cfg.alpha,cfg.M,cfg.v_check);
        case "dense"
            [u_safe,error_vector] = tac_filter_fast(pos,u_aim, ...
                cfg.agent_radius,cfg.safe_distance,cfg.wifi_distance, ...
                cfg.static_obstacle,cfg.obstacle_radius, ...
                cfg.alpha,cfg.M,cfg.v_check);
        otherwise
            error('tac_filter_adapter:filter', ...
                'Unknown filter "%s". Use "sparse" or "dense".', filter_type);
    end
    used_filter = filter_type;
end
